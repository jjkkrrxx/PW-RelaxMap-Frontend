function Star({ fill, large }: { fill: Fill; large?: boolean }) {
  if (large && fill !== 'half') {
    return (
      <svg className={styles.star} viewBox="0 0 32 32" aria-hidden="true">
        <path d={fill === 'full' ? STAR_OUTLINE_FILLED : STAR_OUTLINE} />
      </svg>
    );
  }

  // Порожньої зірки для відображення в макеті немає — малюємо контур тієї ж форми, що й повна.
  return (
    <svg
      className={fill === 'empty' ? styles.empty : styles.star}
      viewBox="0 0 24 24"
      aria-hidden="true"
    >
      <path d={fill === 'half' ? STAR_HALF : STAR_FILLED} />
    </svg>
  );
}

// Рейтинг зірками з підтримкою половинок.
// editable=true — інтерактивний вибір цілої оцінки (для форми відгуку).
export default function StarRating({
  value,
  max = 5,
  editable = false,
  onChange,
  size = 24,
}: Props) {
  const rounded = Math.round(value * 2) / 2; // округлення до 0.5

  const fillFor = (i: number): Fill => {
    if (rounded >= i + 1) return 'full';
    if (rounded >= i + 0.5) return 'half';
    return 'empty';
  };

  return (
    <div
      className={`${styles.stars} ${size === 32 ? styles.large : ''}`}
      role={editable ? 'radiogroup' : 'img'}
      aria-label={editable ? 'Оцінка' : `Рейтинг ${value} з ${max}`}
    >
      {Array.from({ length: max }, (_, i) =>
        editable ? (
          <button
            key={i}
            type="button"
            className={styles.button}
            role="radio"
            aria-checked={rounded === i + 1}
            aria-label={`${i + 1} з ${max}`}
            onClick={() => onChange?.(i + 1)}
          >
            <Star fill={fillFor(i)} large={size === 32} />
          </button>
        ) : (
          <Star key={i} fill={fillFor(i)} />
        ),
      )}
    </div>
  );
}
